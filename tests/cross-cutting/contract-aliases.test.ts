/**
 * Which spelling of an operation should a caller reach for?
 *
 * Several operations in this contract are the same intent written twice — `DELETE /users`,
 * `DELETE /users/{id}` and `DELETE /users/{id}/hard` delete one user three ways; `GET /products`
 * and `POST /products/search` ask one question over two transports. That is deliberate, and
 * `docs/theory/request-input.md` argues why. What it left unsaid is which one is *the* one.
 *
 * "Functionally equivalent to `GET /products`" — the phrasing several descriptions already carry —
 * tells an SDK author the two are interchangeable, which is the one thing they do not need to
 * know. `x-alias-of` says the useful half instead: this operation is the alternate spelling, and
 * THAT one is canonical.
 *
 * ── Why an extension rather than `deprecated` ─────────────────────────────────────────────────
 * `deprecated: true` is the obvious reach and it is wrong. These alternates are supported, not
 * scheduled for removal, and orval marks a deprecated operation — so it would put a warning in
 * the paired frontend on every call to a route this API fully intends to keep. An `x-` extension
 * is ignored by every generator (verified: adding these changed no generated byte), so the
 * annotation costs nothing and the assertions below are what give it teeth.
 */

import { readFileSync } from 'node:fs';
import path from 'node:path';
import { parse } from 'yaml';

const HTTP_METHODS = new Set(['get', 'post', 'put', 'patch', 'delete']);

interface Operation {
    operationId?: string;
    responses?: Record<string, unknown>;
    'x-alias-of'?: string;
}

const spec = parse(readFileSync(path.resolve(__dirname, '../../openapi.yaml'), 'utf8')) as {
    paths: Record<string, Record<string, Operation>>;
};

/** Every operation in the bundle, with the route it is reachable through. */
const operations = Object.entries(spec.paths).flatMap(([route, item]) =>
    Object.entries(item)
        .filter(([method]) => HTTP_METHODS.has(method))
        .map(([method, operation]) => ({ route, method, operation }))
);

const byOperationId = new Map(
    operations
        .filter(({ operation }) => operation.operationId !== undefined)
        .map(({ route, method, operation }) => [
            operation.operationId!,
            { route, method, operation }
        ])
);

const aliases = operations.filter(({ operation }) => operation['x-alias-of'] !== undefined);

/**
 * The schema an operation answers a success with, as a comparable string.
 *
 * Compared rather than merely present, because the claim `x-alias-of` makes is that a caller can
 * switch spellings without changing what they parse. An alias whose 200 returned a different
 * envelope would be a different operation wearing the annotation.
 */
const successSchema = (operation: Operation): string => {
    const responses = operation.responses ?? {};
    const status = Object.keys(responses).find((code) => code.startsWith('2'));
    if (status === undefined) return '';

    // The SCHEMA, not the whole response object. `description` is prose written for a human —
    // "Users list page" against "Users search results" — and holding two spellings to the same
    // sentence would be a spelling test, not a contract one. What a caller parses is the schema.
    const response = responses[status] as {
        content?: Record<string, { schema?: unknown }>;
    };
    return JSON.stringify(response.content?.['application/json']?.schema ?? null);
};

/** The success STATUS an operation answers with — 200 and 201 are not interchangeable. */
const successStatus = (operation: Operation): string =>
    Object.keys(operation.responses ?? {}).find((code) => code.startsWith('2')) ?? '';

describe('operation aliases', () => {
    // A regex-free tripwire: if the bundle is ever read wrong, everything below passes vacuously.
    it('found the operations and the aliases among them', () => {
        expect(operations.length).toBeGreaterThan(50);
        expect(aliases.length).toBeGreaterThan(5);
    });

    it('every x-alias-of names an operation that exists', () => {
        const dangling = aliases
            .filter(({ operation }) => !byOperationId.has(operation['x-alias-of']!))
            .map(({ operation }) => `${operation.operationId} -> ${operation['x-alias-of']}`);

        expect(dangling).toEqual([]);
    });

    // An alias pointing at an alias means nothing is canonical, which is the whole point lost.
    it('no alias points at another alias', () => {
        const chained = aliases
            .filter(
                ({ operation }) =>
                    byOperationId.get(operation['x-alias-of']!)?.operation['x-alias-of'] !==
                    undefined
            )
            .map(({ operation }) => `${operation.operationId} -> ${operation['x-alias-of']}`);

        expect(chained).toEqual([]);
    });

    it('does not name itself', () => {
        const selfReferential = aliases
            .filter(({ operation }) => operation['x-alias-of'] === operation.operationId)
            .map(({ operation }) => operation.operationId);

        expect(selfReferential).toEqual([]);
    });

    /*
     * The load-bearing assertion. Everything above is spelling; this is the claim a caller acts
     * on — swap the spelling, parse the same thing. A mismatch here means the annotation is
     * lying, and the fix is to correct whichever response drifted, not to drop the annotation.
     */
    // A caller switching spellings branches on the status code before it parses anything, so a
    // 201 where its canonical answers 200 breaks the swap just as surely as a different schema.
    it('an alias answers success with the same status as its canonical', () => {
        const divergent = aliases
            .filter(({ operation }) => {
                const canonical = byOperationId.get(operation['x-alias-of']!);
                return (
                    canonical !== undefined &&
                    successStatus(operation) !== successStatus(canonical.operation)
                );
            })
            .map(
                ({ operation }) =>
                    `${operation.operationId} answers ${successStatus(operation)} where ` +
                    `${operation['x-alias-of']} answers ` +
                    successStatus(byOperationId.get(operation['x-alias-of']!)!.operation)
            );

        expect(divergent).toEqual([]);
    });

    it('an alias answers success with the same schema as its canonical', () => {
        const divergent = aliases
            .filter(({ operation }) => {
                const canonical = byOperationId.get(operation['x-alias-of']!);
                return (
                    canonical !== undefined &&
                    successSchema(operation) !== successSchema(canonical.operation)
                );
            })
            .map(
                ({ operation }) =>
                    `${operation.operationId} answers differently from ${operation['x-alias-of']}`
            );

        expect(divergent).toEqual([]);
    });
});
