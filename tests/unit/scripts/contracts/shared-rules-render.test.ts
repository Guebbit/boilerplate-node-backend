import { z } from 'zod';
import { deriveKey, renderGenerated } from '../../../../scripts/contracts/shared-rules-render';
import {
    keyedListSchema,
    type GenerateSpec
} from '../../../../src/infrastructure/config/shared-rules/generate-spec';

/** A spec with one of each shape. */
const spec: GenerateSpec = {
    out: 'src/x.generated.ts',
    exports: [
        { exportName: 'names', shape: 'keyed-list', field: 'names', description: 'The names.' },
        { exportName: 'limits', shape: 'verbatim', field: 'limits', description: 'The limits.' }
    ]
};

describe('deriveKey', () => {
    it('uppercases and turns dots into underscores', () => {
        expect(deriveKey('security.api_key.revoked')).toBe('SECURITY_API_KEY_REVOKED');
        expect(deriveKey('example_published')).toBe('EXAMPLE_PUBLISHED');
    });
});

describe('renderGenerated', () => {
    const output = renderGenerated('x.yaml', spec, {
        names: [
            { value: 'a.b', description: 'First.' },
            { value: 'a.c', description: 'Two\nlines.' }
        ],
        limits: { max: 3, delays: [1, 2], big: [300_000, 1_234_567], label: 'x 12345' }
    });

    it('names the source in a do-not-edit header', () => {
        expect(output).toContain('GENERATED by `npm run regenerate` from `x.yaml`');
    });

    it('writes a keyed list as an as-const object with a docblock per key', () => {
        expect(output).toContain('/** First. */\n    A_B: "a.b"');
        expect(output).toContain('/**\n     * Two\n     * lines.\n     */\n    A_C: "a.c"');
        expect(output).toContain('export const names = {');
        expect(output).toContain('} as const;');
    });

    it('dumps a verbatim field as the parsed data', () => {
        expect(output).toContain('export const limits = {');
        expect(output).toContain('"delays": [\n        1,\n        2\n    ]');
    });

    it('groups long integers in threes and leaves strings alone', () => {
        expect(output).toContain('300_000');
        expect(output).toContain('1_234_567');
        expect(output).toContain('"x 12345"');
    });

    it('refuses a field the document lacks', () => {
        expect(() => renderGenerated('x.yaml', spec, { names: [] })).toThrow(/`limits`/);
    });

    it('refuses two values that derive the same key', () => {
        expect(() =>
            renderGenerated('x.yaml', spec, {
                names: [
                    { value: 'a.b', description: 'x' },
                    { value: 'a_b', description: 'y' }
                ],
                limits: {}
            })
        ).toThrow(/same key/);
    });
});

describe('keyedListSchema', () => {
    const schema = z.strictObject({ list: keyedListSchema(/^[a-z.]+$/) });

    it('accepts a unique list that matches the pattern', () => {
        expect(schema.safeParse({ list: [{ value: 'a.b', description: 'x' }] }).success).toBe(true);
    });

    it.each([
        [
            'a repeated value',
            [
                { value: 'a', description: 'x' },
                { value: 'a', description: 'y' }
            ]
        ],
        ['a value off the pattern', [{ value: 'A', description: 'x' }]],
        ['an empty list', []],
        ['a missing description', [{ value: 'a', description: '' }]]
    ])('refuses %s', (_name, list) => {
        expect(schema.safeParse({ list }).success).toBe(false);
    });
});
