/**
 * @module
 * What a job's declaration turns into: the crontab entry, the `package.json` script line and the
 * table row, and the line-based rewrite of `package.json` that leaves everything around the job
 * scripts untouched.
 */

import type { JobDeclaration } from '@kernel/registry';
import {
    describeSchedule,
    looksLikeCron,
    renderCrontab,
    renderJobsTable,
    withJobScripts
} from '../../../../scripts/docs/jobs-render';

/** A declaration with only what the renderers read. */
const job = (
    name: string,
    schedule: string,
    overrides: Partial<JobDeclaration> = {}
): JobDeclaration => ({
    name,
    schedule,
    summary: `Does the ${name} work.`,
    run: () => Promise.resolve(),
    ...overrides
});

describe('looksLikeCron', () => {
    it.each(['* * * * *', '5 2 * * *', '*/5 * * * *'])('accepts %s', (schedule) => {
        expect(looksLikeCron(schedule)).toBe(true);
    });

    it.each(['', '5 2 * *', '5 2 * * * *', 'nightly'])('refuses %j', (schedule) => {
        expect(looksLikeCron(schedule)).toBe(false);
    });
});

describe('describeSchedule', () => {
    it.each([
        ['* * * * *', 'every minute'],
        ['*/5 * * * *', 'every 5 min'],
        ['5 2 * * *', '02:05 nightly'],
        ['0 14 * * *', '14:00 nightly'],
        ['0 3 * * 1', '`0 3 * * 1`']
    ])('reads %s as %s', (schedule, words) => {
        expect(describeSchedule(schedule)).toBe(words);
    });
});

describe('renderCrontab', () => {
    it('writes one commented entry per job, in declaration order', () => {
        const text = renderCrontab([job('reap:a', '0 2 * * *'), job('sweep:b', '* * * * *')]);

        expect(text).toContain('# Does the reap:a work.\n0 2 * * * cd /app && npm run reap:a\n');
        expect(text.indexOf('reap:a')).toBeLessThan(text.indexOf('sweep:b'));
        expect(text.endsWith('npm run sweep:b\n')).toBe(true);
    });

    it('says it is generated, so nobody edits it by hand', () => {
        expect(renderCrontab([job('reap:a', '0 2 * * *')])).toContain(
            'GENERATED by `npm run jobs:generate`'
        );
    });
});

describe('renderJobsTable', () => {
    it('marks a leased job and words the schedule', () => {
        const table = renderJobsTable([job('reap:a', '5 2 * * *', { lease: { ttlMs: 1000 } })]);

        expect(table).toContain(
            '| `npm run reap:a` | 02:05 nightly | Yes | Does the reap:a work. |'
        );
    });
});

describe('withJobScripts', () => {
    const packageText = [
        '{',
        '    "scripts": {',
        '        "lint": "eslint .",',
        '        "reap:old": "tsx scripts/ops/reap-old.ts",',
        '        "reencrypt": "tsx scripts/ops/reencrypt.ts",',
        '        "sweep:old": "tsx scripts/ops/sweep-old.ts",',
        '        "test": "jest"',
        '    }',
        '}'
    ].join('\n');

    it('replaces every job script with the declared ones, where the first stood', () => {
        const text = withJobScripts(packageText, [
            job('reap:a', '0 2 * * *'),
            job('sweep:b', '* * * * *')
        ]);

        expect(text).toContain(
            '        "reap:a": "tsx scripts/ops/run-job.ts reap:a",\n        "sweep:b": "tsx scripts/ops/run-job.ts sweep:b",\n        "reencrypt"'
        );
        expect(text).not.toContain('reap:old');
        expect(text).not.toContain('sweep:old');
    });

    it('leaves every other line exactly as it was', () => {
        const text = withJobScripts(packageText, []);

        expect(text).toBe(
            [
                '{',
                '    "scripts": {',
                '        "lint": "eslint .",',
                '        "reencrypt": "tsx scripts/ops/reencrypt.ts",',
                '        "test": "jest"',
                '    }',
                '}'
            ].join('\n')
        );
    });
});
