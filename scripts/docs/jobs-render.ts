/**
 * @module
 * The text a job's declaration turns into: its `docker/crontab` entry, its `package.json` script
 * line and its row in the ops page's table. Pure, so a test can hold the output to the declarations
 * without touching the disk; `generate-jobs.ts` is the one that writes.
 */

import type { JobDeclaration } from '@kernel/registry';

/** The script every job's `npm run` line points at. */
const RUNNER = 'tsx scripts/ops/run-job.ts';

/** The five fields of a cron expression. */
const CRON_FIELDS = 5;

/**
 * Whether `schedule` has the five fields cron expects. A shape check, not a parser: supercronic
 * refuses anything it cannot read at boot, and a test of its own grammar is not this repo's job.
 *
 * @param schedule - a declaration's `schedule`
 */
export const looksLikeCron = (schedule: string): boolean =>
    schedule.trim().split(/\s+/).length === CRON_FIELDS;

/**
 * A schedule in words, for the ops table: `5 2 * * *` is "02:05 nightly", a step in the minute
 * field with every other field open is "every N min", and all five open is "every minute".
 * Anything else is shown as the expression itself.
 *
 * @param schedule - a declaration's `schedule`
 */
export const describeSchedule = (schedule: string): string => {
    const [minute, hour, ...rest] = schedule.trim().split(/\s+/);
    if (schedule.trim() === '* * * * *') return 'every minute';
    const every = /^\*\/(\d+)$/.exec(minute)?.[1];
    if (every && hour === '*' && rest.every((field) => field === '*')) return `every ${every} min`;
    if (/^\d+$/.test(minute) && /^\d+$/.test(hour) && rest.every((field) => field === '*'))
        return `${hour.padStart(2, '0')}:${minute.padStart(2, '0')} nightly`;
    return `\`${schedule}\``;
};

/**
 * The `package.json` script line for one job, as written in the file (8 spaces, trailing comma).
 *
 * @param job - the declaration
 */
const scriptLine = (job: JobDeclaration): string =>
    `        "${job.name}": "${RUNNER} ${job.name}",`;

/** Everything above the entries in `docker/crontab`. */
const CRONTAB_HEADER = [
    "# Scheduled jobs for this deployment's `cron` service (docker-compose.yml and",
    '# docker-compose.production.yml). supercronic reads this file from `/app/crontab`.',
    '#',
    '# GENERATED by `npm run jobs:generate` from the `jobs` each module declares on its manifest',
    '# (`AppModule.jobs`) and `src/app/jobs.ts` — edit a declaration, never this file. Deleting a',
    '# module deletes its entries on the next regeneration. See docs/reference/ops.md#scheduled-jobs',
    '# for what each job does and why it is safe to repeat.',
    '#',
    '# `scripts/ops/run-job.ts` gives every entry a non-zero exit on failure, closes its Mongo',
    "# connection on both paths, and records each run's outcome for /observability/health.",
    '#',
    "# No output redirects: supercronic hands each job's stdout/stderr straight to its own",
    "# (`-passthrough-logs`), which is the container's log stream Promtail ships.",
    ''
].join('\n');

/**
 * The whole `docker/crontab`: the header, then one commented entry per job in declaration order.
 *
 * @param jobs - every job in the build
 */
export const renderCrontab = (jobs: readonly JobDeclaration[]): string =>
    `${CRONTAB_HEADER}${jobs
        .map((job) => `# ${job.summary}\n${job.schedule} cd /app && npm run ${job.name}`)
        .join('\n')}\n`;

/**
 * The jobs table of the ops page: one row per job.
 *
 * @param jobs - every job in the build
 */
export const renderJobsTable = (jobs: readonly JobDeclaration[]): string =>
    [
        '| Job | Schedule (UTC) | Leased | What it does |',
        '| --- | --- | --- | --- |',
        ...jobs.map(
            (job) =>
                `| \`npm run ${job.name}\` | ${describeSchedule(job.schedule)} | ${job.lease ? 'Yes' : 'No'} | ${job.summary} |`
        )
    ].join('\n');

/** Whether a `package.json` line is one of the job scripts this file generates. */
const isJobScript = (line: string): boolean => /^\s+"(?:reap|sweep):[\w-]+":/.test(line);

/**
 * `package.json`'s text with its job scripts replaced by `jobs`' own: every `reap:*`/`sweep:*`
 * line removed, the generated ones put where the first of them stood. Line-based on purpose — the
 * file is hand-formatted, and a JSON round-trip would rewrite everything around the scripts.
 *
 * @param packageText - the current file
 * @param jobs - every job in the build
 */
export const withJobScripts = (packageText: string, jobs: readonly JobDeclaration[]): string => {
    const lines = packageText.split('\n');
    const first = lines.findIndex((line) => isJobScript(line));
    const kept = lines.filter((line) => !isJobScript(line));
    const insertAt =
        first === -1 ? kept.findIndex((line) => /^\s+"scripts":/.test(line)) + 1 : first;
    return [
        ...kept.slice(0, insertAt),
        ...jobs.map((job) => scriptLine(job)),
        ...kept.slice(insertAt)
    ].join('\n');
};
