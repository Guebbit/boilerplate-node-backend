/**
 * @module
 * The scenario registries, generated from the file tree instead of listed by hand.
 *
 * Owns:    `scenarios/shop-modules.generated.ts`, `scenarios/scenarios.generated.ts` and
 *          `scenarios/support/doubles/modules.generated.ts`.
 * Reads:   the file names and one `export const` line per file — never its body.
 * Why:     removing a module (or the whole shop) is then only deleting files; the next generation
 *          drops what is gone. No edit has to match text a person may have reworded.
 *
 * Convention, one per registry:
 *
 * | file                                         | export                    | collected as            |
 * | -------------------------------------------- | ------------------------- | ----------------------- |
 * | `scenarios/<module>.ts`                      | `shopModule`              | `shopModuleFixtures`    |
 * | `scenarios/<name>.scenario.ts`               | `scenario`                | `scenarioFixtures`      |
 * | `scenarios/support/doubles/<module>/register.ts` | `registerDouble`      | `registerModuleDoubles` |
 *
 * See: docs/tools/demo-profile.md#how-a-scenario-is-built
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import type { FormatText } from './format-text';

/** One generated file: where it goes, relative to the repo root, and what it should hold. */
export interface GeneratedFile {
    file: string;
    content: string;
}

/** The registry of per-module shop fixtures, relative to the repo root. */
export const FIXTURE_REGISTRY = 'scenarios/shop-modules.generated.ts';

/** The registry of named scenarios, relative to the repo root. Apart from the fixtures: a scenario reads them. */
export const SCENARIO_REGISTRY = 'scenarios/scenarios.generated.ts';

/** The registry of per-module test doubles, relative to the repo root. */
export const DOUBLES_REGISTRY = 'scenarios/support/doubles/modules.generated.ts';

/** The notice every generated file opens with. */
const HEADER = `/**
 * @module
 * GENERATED by \`npm run regenerate\` — do not edit; add or delete the file it collects.
 */
`;

/**
 * Whether a file declares the named export. Read as a line, not parsed: the convention is one
 * `export const <name>` at the top level, which is all this needs to know.
 * @param file - absolute path
 * @param exportName - the export the convention asks for
 */
const declares = (file: string, exportName: string): boolean =>
    new RegExp(String.raw`^export const ${exportName}\b`, 'm').test(readFileSync(file, 'utf8'));

/**
 * A module or scenario name as an identifier: `api-keys` becomes `apiKeys`.
 * @param name - a kebab-case file or folder name
 */
const identifier = (name: string): string =>
    name.replaceAll(/-(\w)/g, (_whole, letter: string) => letter.toUpperCase());

/**
 * Names, alphabetically, of the files in a folder that match a pattern.
 * @param folder - absolute folder, which may not exist
 * @param pattern - the whole file name, with the entry name captured
 */
const namesIn = (folder: string, pattern: RegExp): string[] =>
    existsSync(folder)
        ? readdirSync(folder)
              .flatMap((entry) => pattern.exec(entry)?.[1] ?? [])
              .toSorted()
        : [];

/**
 * Render `import { <exported> as <alias> } from '<from>'` lines and the object that gathers them.
 * @param entries - name, import path and exported symbol of each collected file
 * @param constName - the exported object's name
 * @param description - its docblock text
 */
const renderCollection = (
    entries: readonly { name: string; from: string; exported: string }[],
    constName: string,
    description: string
): { imports: string[]; declaration: string } => ({
    imports: entries.map(
        ({ name, from, exported }) =>
            `import { ${exported} as ${identifier(name)} } from '${from}';`
    ),
    declaration: `/**\n * ${description}\n */\nexport const ${constName} = { ${entries
        .map(({ name }) => (identifier(name) === name ? name : `'${name}': ${identifier(name)}`))
        .join(', ')} };`
});

/**
 * The fixture registry: every module's `shopModule`.
 * @param repoRoot - the checkout to read
 */
const renderFixtureRegistry = (repoRoot: string): string => {
    const scenarios = path.join(repoRoot, 'scenarios');
    const modules = namesIn(scenarios, /^(?!.*\.scenario)([\w-]+)\.ts$/)
        .filter((name) => declares(path.join(scenarios, `${name}.ts`), 'shopModule'))
        .map((name) => ({ name, from: `./${name}`, exported: 'shopModule' }));
    const fixtures = renderCollection(
        modules,
        'shopModuleFixtures',
        "Each module's `shop` fixtures, by module name — `scenarios/shop-modules.ts` types and reads them."
    );
    return [HEADER, fixtures.imports.join('\n'), '', fixtures.declaration, ''].join('\n');
};

/**
 * The scenario registry: every `<name>.scenario.ts`.
 * @param repoRoot - the checkout to read
 * @throws {Error} when a scenario file exports no `scenario`
 */
const renderScenarioRegistry = (repoRoot: string): string => {
    const scenarios = path.join(repoRoot, 'scenarios');
    const named = namesIn(scenarios, /^([\w-]+)\.scenario\.ts$/).map((name) => ({
        name,
        from: `./${name}.scenario`,
        exported: 'scenario'
    }));

    for (const { name } of named)
        if (!declares(path.join(scenarios, `${name}.scenario.ts`), 'scenario'))
            throw new Error(`[scenarios] ${name}.scenario.ts exports no \`scenario\`.`);

    const table = renderCollection(
        named,
        'scenarioFixtures',
        'Every `<name>.scenario.ts`, by name — `scenarios/index.ts` adds `blank` and registers them.'
    );
    return [HEADER, table.imports.join('\n'), '', table.declaration, ''].join('\n');
};

/**
 * The doubles registry: one call per module folder that carries a `register.ts`.
 * @param repoRoot - the checkout to read
 */
const renderDoublesRegistry = (repoRoot: string): string => {
    const doubles = path.join(repoRoot, 'scenarios', 'support', 'doubles');
    const folders = existsSync(doubles)
        ? readdirSync(doubles, { withFileTypes: true })
              .filter((entry) => entry.isDirectory())
              .map((entry) => entry.name)
              .filter((name) => declares(path.join(doubles, name, 'register.ts'), 'registerDouble'))
              .toSorted()
        : [];

    return [
        HEADER,
        ...folders.map(
            (name) =>
                `import { registerDouble as ${identifier(name)}Double } from './${name}/register';`
        ),
        '',
        '/** The `registerDouble` of each module that has a folder here. */',
        `const doubles: readonly (() => void)[] = [${folders.map((name) => `${identifier(name)}Double`).join(', ')}];`,
        '',
        '/**',
        ' * Registers the doubles of every module that has a folder here. Called by `./register.ts`;',
        ' * deleting a module deletes its folder, and the next generation drops its entry.',
        ' */',
        'export const registerModuleDoubles = (): void => {',
        '    for (const register of doubles) register();',
        '};',
        ''
    ].join('\n');
};

/**
 * What the registries should hold for the tree at `repoRoot`, formatted the way `prettier:check`
 * wants it.
 * @param repoRoot - the checkout to read
 * @param format - the formatter (`formatWithRepoConfig`); passed in because importing it loads
 *   Prettier, which a unit test cannot do under Jest
 */
export const renderScenarioRegistries = (
    repoRoot: string,
    format: FormatText
): Promise<GeneratedFile[]> =>
    // Inside a `then`, so a refused file rejects the promise instead of throwing past the caller.
    Promise.resolve().then(() =>
        Promise.all(
            [
                { file: FIXTURE_REGISTRY, content: renderFixtureRegistry(repoRoot) },
                { file: SCENARIO_REGISTRY, content: renderScenarioRegistry(repoRoot) },
                { file: DOUBLES_REGISTRY, content: renderDoublesRegistry(repoRoot) }
            ].map(({ file, content }) =>
                format(repoRoot, path.join(repoRoot, file), content).then((formatted) => ({
                    file,
                    content: formatted
                }))
            )
        )
    );

/**
 * Write the registries, reporting which ones changed.
 * @param repoRoot - the checkout to write into
 * @param format - see {@link renderScenarioRegistries}
 * @returns the repo-relative paths whose content changed
 */
export const writeScenarioRegistries = (repoRoot: string, format: FormatText): Promise<string[]> =>
    renderScenarioRegistries(repoRoot, format).then((files) =>
        files.flatMap(({ file, content }) => {
            const target = path.join(repoRoot, file);
            if (existsSync(target) && readFileSync(target, 'utf8') === content) return [];
            mkdirSync(path.dirname(target), { recursive: true });
            writeFileSync(target, content, 'utf8');
            return [file];
        })
    );

/**
 * The registries that no longer match the tree — what `--check` reports.
 * @param repoRoot - the checkout to compare
 * @param format - see {@link renderScenarioRegistries}
 * @returns the repo-relative paths that are stale or missing
 */
export const staleScenarioRegistries = (repoRoot: string, format: FormatText): Promise<string[]> =>
    renderScenarioRegistries(repoRoot, format).then((files) =>
        files
            .filter(({ file, content }) => {
                const target = path.join(repoRoot, file);
                return !existsSync(target) || readFileSync(target, 'utf8') !== content;
            })
            .map(({ file }) => file)
    );
