#!/usr/bin/env tsx
/*
 * Generates the accepted upload types from `openapi.yaml`: every multipart `imageUpload` part
 * declares `encoding.imageUpload.contentType`, stamped there by the bundler from the root's
 * `x-image-upload-types`. The backend's `fileFilter` and the frontend's file picker both read the
 * result, so the contract is the one place the list is written.
 *
 * Refuses a contract whose upload bodies disagree, or declare none: one list for the whole API.
 *
 * Written beside the backend's other generated contract files under `api/`; the frontend keeps its
 * own copy of this script, which writes under its `contracts/` folder.
 *
 * `--check` writes nothing and exits 1 on a mismatch (the shared `writeOrCheck` helper).
 *
 * Usage: tsx scripts/contracts/generate-upload-types.ts --out <path> [--check]
 */
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeOrCheck } from './generated-file';
import { parse } from 'yaml';
import { requiredPath } from '../cli';

/** The slice of an OpenAPI media type this generator reads. */
interface MediaType {
    encoding?: { imageUpload?: { contentType?: string } };
}

/** The slice of the bundled document this generator reads. */
interface OpenApiDocument {
    paths: Record<
        string,
        Record<string, { requestBody?: { content?: Record<string, MediaType> } }>
    >;
}

/** The repo root. `import.meta.url` rather than `__dirname`: this script runs as ESM. */
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

/** The bundled root contract this generator reads. */
const INPUT = path.resolve(ROOT, 'openapi.yaml');

/** Absolute path of the file to generate, from `--out`. */
const OUTPUT = requiredPath('out', ROOT);

/**
 * The bundled contract, parsed. `parse` is the `yaml` package's YAML 1.2 loader; the `as` narrows
 * its `any` to the slice this file reads. https://eemeli.org/yaml/#yaml-parse
 */
const document = parse(readFileSync(INPUT, 'utf8')) as OpenApiDocument;

/** Each distinct `imageUpload` contentType the contract declares, with the operations naming it. */
const declared = new Map<string, string[]>();

for (const [route, operations] of Object.entries(document.paths))
    for (const [method, operation] of Object.entries(operations)) {
        const contentType =
            operation.requestBody?.content?.['multipart/form-data']?.encoding?.imageUpload
                ?.contentType;
        if (contentType !== undefined)
            declared.set(contentType, [
                ...(declared.get(contentType) ?? []),
                `${method.toUpperCase()} ${route}`
            ]);
    }

if (declared.size !== 1) {
    console.error(
        declared.size === 0
            ? 'No multipart body declares `encoding.imageUpload.contentType`.'
            : `Upload bodies disagree on the accepted types:\n${[...declared]
                  .map(([types, where]) => `  ${types}: ${where.join(', ')}`)
                  .join('\n')}`
    );
    process.exit(1);
}

/** The accepted media types, in the order the contract lists them. */
const [accepted = ''] = declared.keys();
const types = accepted.split(',').map((type) => type.trim());

/** The whole file's text. */
const output =
    '// Code generated by `npm run gen:api`. DO NOT EDIT.\n' +
    '/*\n' +
    ' * GENERATED — do not edit manually.\n' +
    ' * Source: openapi.yaml  |  Regenerate: npm run gen:api\n' +
    ' */\n\n' +
    '/** The media types every `imageUpload` part accepts, as the contract declares them. */\n' +
    `export const ACCEPTED_UPLOAD_TYPES = ${JSON.stringify(types)} as const;\n\n` +
    '/** One accepted upload media type. */\n' +
    'export type AcceptedUploadType = (typeof ACCEPTED_UPLOAD_TYPES)[number];\n';

// Write the file, or under `--check` compare it with what is on disk.
writeOrCheck(OUTPUT, output, 'openapi.yaml');
