#!/usr/bin/env tsx
/*
 * Generates the closed sets a redirect puts in its query string from `openapi.yaml`: every `302`
 * that declares `x-redirect-query` (a map of parameter name to an enum schema) becomes one row,
 * keyed by operation id then parameter. The OAuth callback's `?error=` codes are the case: the
 * redirect the browser follows is the only place a client learns why the round trip failed.
 *
 * Why not a component schema: the bundler inlines a `$ref` under an `x-` key and prunes the
 * component, so the list is written inline in the fragment and read here.
 *
 * Written beside the backend's other generated contract files under `api/`; the frontend's
 * route-table generator writes the same table into its own routes file.
 *
 * `--check` writes nothing and exits 1 on a mismatch (the shared `writeOrCheck` helper).
 *
 * Usage: tsx scripts/contracts/generate-redirect-query.ts --out <path> [--check]
 */
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { requiredPath } from '../cli';
import { writeOrCheck } from './generated-file';
import { operationsOf, parseOpenApi, type Operation } from './openapi-document';

/** What a fragment's `x-redirect-query` holds on a response: parameter name to its enum schema. */
type RedirectQuery = Record<string, { enum?: string[] }>;

/** The repo root. `import.meta.url` rather than `__dirname`: this script runs as ESM. */
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

/** The bundled root contract this generator reads. */
const INPUT = path.resolve(ROOT, 'openapi.yaml');

/** Absolute path of the file to generate, from `--out`. */
const OUTPUT = requiredPath('out', ROOT);

/** Operation id to parameter name to the values it takes. */
const enums: Record<string, Record<string, string[]>> = {};

/** Records every `x-redirect-query` enum one operation's responses declare. */
const collectEnums = (operation: Operation): void => {
    for (const response of Object.values(operation.responses ?? {})) {
        // `x-redirect-query` is a vendor key on the response, which the OpenAPI types do not declare.
        const query = (response as { 'x-redirect-query'?: RedirectQuery })['x-redirect-query'];
        for (const [parameter, schema] of Object.entries(query ?? {}))
            if (operation.operationId && schema.enum)
                (enums[operation.operationId] ??= {})[parameter] = schema.enum;
    }
};

for (const { operation } of operationsOf(parseOpenApi(readFileSync(INPUT, 'utf8'))))
    collectEnums(operation);

/** The whole file's text. */
const output =
    '// Code generated by `npm run gen:api`. DO NOT EDIT.\n' +
    '/*\n' +
    ' * GENERATED — do not edit manually.\n' +
    ' * Source: openapi.yaml  |  Regenerate: npm run gen:api\n' +
    ' */\n\n' +
    '/**\n' +
    ' * The values a redirect puts in a query parameter, by operation id then parameter name — the\n' +
    " * contract's `x-redirect-query`.\n" +
    ' */\n' +
    `export const REDIRECT_QUERY_ENUMS = ${JSON.stringify(enums, null, 4)} as const;\n`;

// Write the file, or under `--check` compare it with what is on disk.
writeOrCheck(OUTPUT, output, 'openapi.yaml');
