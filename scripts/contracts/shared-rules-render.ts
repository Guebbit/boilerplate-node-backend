/**
 * @module
 * Pure half of the shared-rules code generator: turn a parsed rules document and its
 * {@link GenerateSpec} into the text of a `.generated.ts`. No filesystem, so a test can walk it.
 *
 * See: docs/theory/shared-rules.md
 */

import type {
    GeneratedExport,
    GenerateSpec,
    KeyedEntry
} from '../../src/infrastructure/config/shared-rules/generate-spec';

/**
 * The constant key of a wire string: uppercase, `.` to `_`.
 *
 * @param value - `security.api_key.revoked`
 * @returns `SECURITY_API_KEY_REVOKED`
 */
export const deriveKey = (value: string): string => value.toUpperCase().replaceAll('.', '_');

/**
 * A docblock for one line of text or several.
 *
 * @param text - the description
 * @param indent - the block's left margin
 * @returns the comment, one line when it fits on one
 */
const docblock = (text: string, indent = ''): string => {
    const lines = text.trim().split('\n');
    if (lines.length === 1) return `${indent}/** ${lines[0] ?? ''} */`;
    return [
        `${indent}/**`,
        ...lines.map((line) => `${indent} * ${line}`.trimEnd()),
        `${indent} */`
    ].join('\n');
};

/**
 * The slice of the document an export reads.
 *
 * @param document - the parsed rules file
 * @param field - the top-level field, or the whole document when absent
 * @returns that slice
 * @throws {Error} when the field is not in the document
 */
const sliceOf = (document: unknown, field: string | undefined): unknown => {
    if (field === undefined) return document;
    if (typeof document !== 'object' || document === null || !(field in document))
        throw new Error(`the rules file has no \`${field}\` field`);
    return (document as Record<string, unknown>)[field];
};

/**
 * Writes a `keyed-list` as an object literal with one docblock per key.
 *
 * @param entries - the validated list
 * @returns the literal's text
 * @throws {Error} when two values derive the same key
 */
const renderKeyed = (entries: readonly KeyedEntry[]): string => {
    const keys = entries.map((entry) => deriveKey(entry.value));
    if (new Set(keys).size !== keys.length) throw new Error('two values derive the same key');
    const rows = entries.map(
        (entry, index) =>
            `${docblock(entry.description, '    ')}\n    ${keys[index] ?? ''}: ${JSON.stringify(entry.value)}`
    );
    return `{\n${rows.join(',\n')}\n} as const`;
};

/**
 * Groups every integer of five or more digits in threes (`300000` becomes `300_000`), the form
 * `unicorn/numeric-separators-style` demands. String literals are skipped.
 *
 * @param json - JSON text
 * @returns the same text with separators
 */
const withNumericSeparators = (json: string): string =>
    json.replaceAll(/("(?:[^"\\]|\\.)*")|\b\d{5,}\b/g, (match, quoted: string | undefined) =>
        quoted === undefined ? match.replaceAll(/\B(?=(\d{3})+$)/g, '_') : match
    );

/**
 * One exported constant.
 *
 * @param document - the parsed rules file
 * @param spec - which constant to write
 * @returns its docblock and declaration
 */
const renderExport = (document: unknown, spec: GeneratedExport): string => {
    const slice = sliceOf(document, spec.field);
    const literal =
        spec.shape === 'keyed-list'
            ? renderKeyed(slice as readonly KeyedEntry[])
            : `${withNumericSeparators(JSON.stringify(slice, undefined, 4))} as const`;
    return `${docblock(spec.description)}\nexport const ${spec.exportName} = ${literal};\n`;
};

/**
 * The whole generated module, before Prettier.
 *
 * @param source - repo-relative path of the YAML, named in the header
 * @param spec - what to write
 * @param document - the parsed, schema-checked rules file
 * @returns the file's text
 */
export const renderGenerated = (source: string, spec: GenerateSpec, document: unknown): string =>
    [
        `/**\n * @module\n * GENERATED by \`npm run regenerate\` from \`${source}\` — do not edit; edit the YAML.\n */\n`,
        ...spec.exports.map((exported) => renderExport(document, exported))
    ].join('\n');
